package summary

import (
	"bytes"
	"fmt"
	"html/template"
	"time"

	"github.com/albachteng/airgradient/internal/db"
)

type Summary struct {
	PeriodStart  time.Time
	PeriodEnd    time.Time
	OwnStats     []db.PlacementStats
	ChicagoStats []db.LocationStats
}

type Store interface {
	OwnStatsByPlacement(from, to time.Time) ([]db.PlacementStats, error)
	ChicagoStatsByLocation(from, to time.Time) ([]db.LocationStats, error)
}

func Generate(store Store, from, to time.Time) (Summary, error) {
	own, err := store.OwnStatsByPlacement(from, to)
	if err != nil {
		return Summary{}, fmt.Errorf("own stats: %w", err)
	}
	chicago, err := store.ChicagoStatsByLocation(from, to)
	if err != nil {
		return Summary{}, fmt.Errorf("chicago stats: %w", err)
	}
	return Summary{
		PeriodStart:  from,
		PeriodEnd:    to,
		OwnStats:     own,
		ChicagoStats: chicago,
	}, nil
}

